public class Loops {
    public static void main(String[] args) {
        // For loop example
        for (int i = 1; i <= 20; i++) {
            System.out.println(i);
        }
        
        // While loop example
        int j = 0;
        while(j <= 20) {
            System.out.println(j);
            j++;
        }
    }
}



